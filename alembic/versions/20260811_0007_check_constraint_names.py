"""Converge doubled CHECK constraint names onto the canonical model names.

Revision ID: 20260811_0007
Revises: 20260801_0006
Create Date: 2026-08-11

``NAMING_CONVENTION["ck"]`` is ``ck_%(table_name)s_%(constraint_name)s``: the models pass
a *short* name (``area``) and the convention expands it to ``ck_cohort_..._area``.
Revisions 0003, 0004, and 0006 instead passed the *already expanded* name, so the
convention prefixed it a second time and the database physically stored
``ck_cohort_accounting_checks_ck_cohort_accounting_checks_area``.

That is real drift, not a comparison artifact: the migrated database and a
``create_all`` database genuinely disagree on 21 constraint names across 7 tables.
Alembic 1.19.1 began diffing CHECK constraints during autogenerate and made it visible;
1.18.5 simply never looked. The fix therefore has to change the *physical* schema, not
the comparison.

Revisions 0003, 0004, and 0006 are left exactly as they shipped. A revision must mean
the same thing forever, and rewriting them would fix only databases that have never been
built while leaving every existing one silently wrong. This revision converges the
databases that exist.

Backend differences this revision has to absorb
-----------------------------------------------

The doubled name is what SQLAlchemy *asked* for; it is not always what the backend
*stored*. Names generated by a naming convention are ``conv`` labels, which SQLAlchemy
truncates to fit ``max_identifier_length`` as ``name[: max - 8] + "_" + md5(name)[-4:]``.

* **SQLite** has no practical identifier limit, so all 21 are stored in full.
* **PostgreSQL** caps identifiers at 63 characters. 19 of the 21 exceed that and are
  stored truncated with a 4-character hash suffix; the remaining 2
  (``..._area`` at 60 and ``..._finding`` at 63) are stored whole.

So the physical name is backend-dependent and cannot be assumed. This revision asks the
live dialect what it would have produced and matches that against the constraints the
database actually reports, rather than hard-coding either backend's spelling.

Renaming is likewise backend-specific. PostgreSQL renames a constraint in place with
``ALTER TABLE ... RENAME CONSTRAINT``, which touches no row and keeps every index,
foreign key, and dependent object intact. SQLite cannot rename a CHECK constraint at all
— the name lives inside the stored ``CREATE TABLE`` text — so it needs a batch table
rebuild, which is used *only* there.

Fail-closed
-----------

Every rename is resolved to exactly one existing constraint before any DDL runs. A
missing constraint, an unexpected constraint, or two candidates for one target aborts
the revision with the names involved instead of guessing which one to rename.
"""

