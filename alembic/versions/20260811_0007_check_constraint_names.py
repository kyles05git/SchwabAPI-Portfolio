class Rename(NamedTuple):
    """One resolved rename: constraint ``old`` on ``table`` must become ``new``."""

    table: str
    old: str
    new: str
    sqltext: str


def doubled_name(table: str, canonical: str) -> str:
    """The name the convention produced when a revision passed ``canonical`` as the name.

    ``ck_%(table_name)s_%(constraint_name)s`` applied to an already-expanded name.
    """
    return f"ck_{table}_{canonical}"


def stored_name(dialect: Dialect, name: str) -> str:
    """What ``dialect`` physically stores for a convention-generated ``name``.

    ``conv`` marks the name as convention-generated, which is what makes SQLAlchemy
    truncate rather than reject it past ``max_identifier_length`` — the same code path
    that wrote the name originally, so the two agree by construction instead of by a
    reimplemented hash. ``_alembic_quote=False`` asks for the bare stored name; it is
    the documented integration point Alembic itself uses to read a constraint's name
    back without quoting.
    """
    rendered = dialect.identifier_preparer.truncate_and_render_constraint_name(
        conv(name), _alembic_quote=False
    )
    return str(rendered)


def _truncation_prefix(dialect: Dialect, name: str) -> str | None:
    """The fixed leading part a truncated form of ``name`` would keep, else ``None``."""
    limit = dialect.max_constraint_name_length or dialect.max_identifier_length
    if not limit or len(name) <= limit:
        return None
    return name[: limit - 8]


def _resolve(
    dialect: Dialect,
    table: str,
    present: dict[str, str],
    *,
    target: str,
    source: str,
    doubled: str,
) -> Rename | None:
    """Resolve one constraint to a rename, a no-op, or a fail-closed error."""
    if target in present and source in present:
        raise RuntimeError(
            f"ambiguous CHECK constraints on {table!r}: both the canonical name "
            f"{target!r} and the legacy name {source!r} exist. Resolve by hand; this "
            "revision will not guess which one the models are meant to match."
        )
    if target in present:
        return None
    if source in present:
        return Rename(table=table, old=source, new=target, sqltext=present[source])

    prefix = _truncation_prefix(dialect, doubled)
    near = sorted(n for n in present if prefix and n.startswith(prefix))
    if near:
        raise RuntimeError(
            f"ambiguous CHECK constraint on {table!r}: expected {source!r} for target "
            f"{target!r} but found only {near!r}. A truncated name that does not match "
            "the hash this dialect computes cannot be resolved safely; resolve by hand."
        )
    raise RuntimeError(
        f"missing CHECK constraint on {table!r}: neither the canonical name {target!r} "
        f"nor the legacy name {source!r} exists. Present: {sorted(present)!r}"
    )


def plan(bind: Connection, *, to_canonical: bool = True) -> list[Rename]:
    """Every rename still outstanding, resolved against the database's real constraints.

    Returns an empty list when the database already matches, which is what makes this
    revision safe to re-inspect and safe on a ``create_all`` database that never carried
    the doubled names.
    """
    inspector = sa.inspect(bind)
    dialect = bind.dialect
    tables = set(inspector.get_table_names())

    renames: list[Rename] = []
    for table, canonical in CANONICAL_CHECKS:
        if table not in tables:
            raise RuntimeError(
                f"missing table {table!r}: revisions 0003, 0004, and 0006 create every "
                "table this revision converges, so its absence means the chain did not "
                "run as declared."
            )
        present = {
            check["name"]: str(check.get("sqltext") or "")
            for check in inspector.get_check_constraints(table)
            if check.get("name")
        }
        doubled = doubled_name(table, canonical)
        legacy = stored_name(dialect, doubled)
        target, source = (canonical, legacy) if to_canonical else (legacy, canonical)
        resolved = _resolve(
            dialect, table, present, target=target, source=source, doubled=doubled
        )
        if resolved is not None:
            renames.append(resolved)
    return renames


def postgresql_rename_statement(dialect: Dialect, rename: Rename) -> str:
    """The in-place PostgreSQL rename for ``rename``, with identifiers quoted.

    Kept separate from :func:`_apply` so the emitted DDL can be asserted against the
    PostgreSQL dialect without a server, credentials, or a socket.
    """
    preparer = dialect.identifier_preparer
    return (
        f"ALTER TABLE {preparer.quote(rename.table)} "
        f"RENAME CONSTRAINT {preparer.quote(rename.old)} "
        f"TO {preparer.quote(rename.new)}"
    )


def _apply(renames: list[Rename]) -> None:
    """Rename in place on PostgreSQL; rebuild the table only where SQLite forces it."""
    if not renames:
        return

    bind = op.get_bind()
    dialect = bind.dialect

    if dialect.name == "postgresql":
        for rename in renames:
            # Native, metadata-only: no row is read or rewritten, and every index,
            # foreign key, and unique constraint on the table is untouched.
            op.execute(sa.text(postgresql_rename_statement(dialect, rename)))
        return

    if dialect.name == "sqlite":
        # SQLite stores the constraint name inside the table's CREATE TABLE text and
        # offers no way to rename it, so the table must be rebuilt. Batch mode copies
        # every row and re-declares the columns, primary key, foreign keys, unique
        # constraints, indexes, and unrelated CHECK constraints it reflected.
        by_table: dict[str, list[Rename]] = {}
        for rename in renames:
            by_table.setdefault(rename.table, []).append(rename)
        for table, table_renames in by_table.items():
            with op.batch_alter_table(table, recreate="always") as batch_op:
                for rename in table_renames:
                    # ``conv`` on *both* names is load-bearing. Alembic builds these
                    # constraints against a MetaData carrying the model's naming
                    # convention, so a bare string here would be expanded again — the
                    # exact defect this revision exists to undo, applied a third time.
                    batch_op.drop_constraint(conv(rename.old), type_="check")
                    batch_op.create_check_constraint(
                        conv(rename.new), sa.text(rename.sqltext)
                    )
        return

    raise NotImplementedError(
        f"cannot converge CHECK constraint names on dialect {dialect.name!r}; "
        "only postgresql and sqlite are supported backends"
    )


def upgrade() -> None:
    _apply(plan(op.get_bind(), to_canonical=True))


def downgrade() -> None:
    _apply(plan(op.get_bind(), to_canonical=False))
